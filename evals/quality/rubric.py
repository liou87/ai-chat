"""
回答质量的评分标准：评分模型的提示词和标注网页上给人看的说明用同一份，保证人和模型按同一把尺子打分。
"""

DIMENSIONS = {
    "faithful": {
        "label": "忠实度",
        "pass": "回答里关于资料内容的说法都能在资料中找到依据；资料里没有答案时明确说没找到。可以补充常识或建议，但要让人看得出那不是来自资料。",
        "fail": "编造了资料里没有的具体事实、数字、名称或结论；把常识或猜测说成是资料里写的；资料没有答案却给出一个看起来有依据的答案。",
        "na": None,
    },
    "cited": {
        "label": "出处",
        "pass": "用了资料就写出所用资料的标题，而且这些标题确实在资料列表里、确实是答案所依据的那篇。",
        "fail": "用了资料却没有注明出处；注明的标题不在资料列表里，或者张冠李戴（标了 A 篇，内容其实来自 B 篇或不来自任何资料）。",
        "na": "回答没有用任何资料（比如资料都不相关、如实说了没找到），不需要出处。",
    },
    "complete": {
        "label": "回答到位",
        "pass": "直接回答了用户问的问题，核心信息没有遗漏；对比类问题两边都讲到；资料里确实没有答案时，如实说明并给出合理的下一步也算到位。",
        "fail": "答非所问；漏掉了问题的核心；对比类问题只讲了一边；资料里明明有答案却说找不到。",
        "na": None,
    },
}

SYSTEM_PROMPT = (
    "你是严格的评审，负责评估一个个人知识库助手的回答质量。助手先检索了用户的资料，再根据资料回答。"
    "你会看到：用户的问题、助手这次检索/调用工具拿到的全部资料、助手的最终回答。"
    "只依据这些材料判断，不要用你自己对这个话题的了解去补全或纠正资料。\n\n"
    "按下面三个维度分别给出判定：\n"
    + "\n".join(
        f"【{d['label']}】（字段 {key}）\n  通过（pass）：{d['pass']}\n  不通过（fail）：{d['fail']}"
        + (f"\n  不适用（na）：{d['na']}" if d["na"] else "")
        for key, d in DIMENSIONS.items()
    )
    + "\n\n只输出 JSON，格式：{\"faithful\": {\"verdict\": \"pass|fail\", \"reason\": \"一句话理由\"}, "
      "\"cited\": {\"verdict\": \"pass|fail|na\", \"reason\": \"...\"}, \"complete\": {\"verdict\": \"pass|fail\", \"reason\": \"...\"}}。"
      "理由要具体，指出是哪句话、哪篇资料。拿不准时按更严格的一边判。"
)


def render_case(item: dict) -> str:
    """把一条回答整理成评分模型看到的输入。"""
    if item["materials"]:
        mats = "\n\n".join(f"[资料 {i}] 标题：{m['title']}（来自 {m['tool']}）\n{m['content']}"
                           for i, m in enumerate(item["materials"], 1))
    else:
        mats = "（助手这次没有调用任何工具，没有拿到资料）"
    return f"## 用户的问题\n{item['question']}\n\n## 助手拿到的资料\n{mats}\n\n## 助手的回答\n{item['reply']}"
